package ocr

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"strings"

	openapi "github.com/alibabacloud-go/darabonba-openapi/v2/client"
	ocrclient "github.com/alibabacloud-go/ocr-api-20210707/v3/client"
	"github.com/alibabacloud-go/tea/tea"
	"github.com/gogf/gf/v2/frame/g"
)

// BusinessLicenseResult contains the fields used to prefill the company
// verification form after a successful business-license recognition.
type BusinessLicenseResult struct {
	CompanyName             string
	UnifiedSocialCreditCode string
	BusinessAddress         string
}

type businessLicenseData struct {
	CompanyName     string `json:"companyName"`
	CreditCode      string `json:"creditCode"`
	BusinessAddress string `json:"businessAddress"`
}

type businessLicenseResponse struct {
	Data    businessLicenseData `json:"data"`
	Message string              `json:"message"`
}

// RecognizeBusinessLicense calls Alibaba Cloud OCR with a temporary image URL.
// The image URL is generated by the backend for a private OSS object, so no
// AccessKey or permanent public URL is exposed to the mini-program.
func RecognizeBusinessLicense(ctx context.Context, imageURL string) (BusinessLicenseResult, error) {
	imageURL = strings.TrimSpace(imageURL)
	if imageURL == "" {
		return BusinessLicenseResult{}, fmt.Errorf("business license image URL is empty")
	}

	accessKeyID := configValue(ctx, "oss.access_key_id", "OSS_ACCESS_KEY_ID")
	accessKeySecret := configValue(ctx, "oss.access_key_secret", "OSS_ACCESS_KEY_SECRET")
	if accessKeyID == "" || accessKeySecret == "" {
		return BusinessLicenseResult{}, fmt.Errorf("oss access key is not configured")
	}
	endpoint := configValue(ctx, "ocr.endpoint", "OCR_ENDPOINT")
	if endpoint == "" {
		endpoint = "ocr-api.cn-hangzhou.aliyuncs.com"
	}

	client, err := ocrclient.NewClient(&openapi.Config{
		AccessKeyId:     tea.String(accessKeyID),
		AccessKeySecret: tea.String(accessKeySecret),
		Endpoint:        tea.String(endpoint),
	})
	if err != nil {
		return BusinessLicenseResult{}, fmt.Errorf("initialize aliyun OCR client: %w", err)
	}
	response, err := client.RecognizeBusinessLicense(&ocrclient.RecognizeBusinessLicenseRequest{
		Url: tea.String(imageURL),
	})
	if err != nil {
		return BusinessLicenseResult{}, fmt.Errorf("recognize business license: %w", err)
	}
	if response == nil || response.Body == nil {
		return BusinessLicenseResult{}, fmt.Errorf("recognize business license returned an empty response")
	}
	if code := strings.TrimSpace(tea.StringValue(response.Body.Code)); code != "" && code != "200" {
		message := strings.TrimSpace(tea.StringValue(response.Body.Message))
		if message == "" {
			message = "aliyun OCR returned code " + code
		}
		return BusinessLicenseResult{}, fmt.Errorf("%s", message)
	}
	dataJSON := strings.TrimSpace(tea.StringValue(response.Body.Data))
	if dataJSON == "" {
		return BusinessLicenseResult{}, fmt.Errorf("aliyun OCR returned no recognition data")
	}
	var payload businessLicenseResponse
	if err := json.Unmarshal([]byte(dataJSON), &payload); err != nil {
		return BusinessLicenseResult{}, fmt.Errorf("decode aliyun OCR response: %w", err)
	}
	result := BusinessLicenseResult{
		CompanyName:             strings.TrimSpace(payload.Data.CompanyName),
		UnifiedSocialCreditCode: strings.TrimSpace(payload.Data.CreditCode),
		BusinessAddress:         strings.TrimSpace(payload.Data.BusinessAddress),
	}
	if result.CompanyName == "" && result.UnifiedSocialCreditCode == "" && result.BusinessAddress == "" {
		message := strings.TrimSpace(payload.Message)
		if message == "" {
			message = "未识别到有效的营业执照信息"
		}
		return BusinessLicenseResult{}, fmt.Errorf("%s", message)
	}
	return result, nil
}

func configValue(ctx context.Context, key, envKey string) string {
	if value := strings.TrimSpace(os.Getenv(envKey)); value != "" {
		return value
	}
	value, err := g.Cfg().Get(ctx, key)
	if err != nil || value == nil {
		return ""
	}
	return strings.TrimSpace(value.String())
}
