CREATE TABLE procurement_requirements (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    buyer_user_id BIGINT UNSIGNED NOT NULL,
    category_id BIGINT UNSIGNED NOT NULL,
    category_name_snapshot VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    quantity DECIMAL(18, 3) NOT NULL DEFAULT 0,
    stock_unit_id BIGINT UNSIGNED NOT NULL,
    stock_unit_name_snapshot VARCHAR(50) NOT NULL,
    title VARCHAR(200) NULL,
    description TEXT NULL,
    delivery_address VARCHAR(500) NOT NULL,
    expected_delivery_date DATE NULL,
    contact_name VARCHAR(50) NOT NULL,
    contact_phone VARCHAR(30) NOT NULL,
    review_status TINYINT UNSIGNED NOT NULL DEFAULT 0,
    review_reason VARCHAR(500) NULL,
    reviewed_by BIGINT UNSIGNED NULL,
    reviewed_at DATETIME(3) NULL,
    status TINYINT UNSIGNED NOT NULL DEFAULT 0,
    published_at DATETIME(3) NULL,
    expires_at DATETIME(3) NULL,
    response_count INT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    deleted_at DATETIME(3) NULL,
    PRIMARY KEY (id),
    KEY idx_procurement_requirements_buyer_status (buyer_user_id, status),
    KEY idx_procurement_requirements_category_status (category_id, review_status, status),
    KEY idx_procurement_requirements_expires (expires_at, status),
    KEY idx_procurement_requirements_created (created_at),
    CONSTRAINT fk_procurement_requirements_buyer FOREIGN KEY (buyer_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_procurement_requirements_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT fk_procurement_requirements_stock_unit FOREIGN KEY (stock_unit_id) REFERENCES stock_units (id) ON DELETE RESTRICT,
    CONSTRAINT fk_procurement_requirements_reviewer FOREIGN KEY (reviewed_by) REFERENCES admin_users (id) ON DELETE SET NULL,
    CONSTRAINT chk_procurement_requirements_quantity CHECK (quantity >= 0),
    CONSTRAINT chk_procurement_requirements_review_status CHECK (review_status IN (0, 1, 2)),
    CONSTRAINT chk_procurement_requirements_status CHECK (status IN (0, 1, 2, 3, 4, 5))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE procurement_requirement_attribute_values (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    requirement_id BIGINT UNSIGNED NOT NULL,
    attribute_id BIGINT UNSIGNED NOT NULL,
    value_number DECIMAL(18, 6) NULL,
    value_text VARCHAR(1000) NULL,
    value_bool TINYINT UNSIGNED NULL,
    value_option_id BIGINT UNSIGNED NULL,
    value_json JSON NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_procurement_requirement_attribute (requirement_id, attribute_id),
    KEY idx_procurement_requirement_attribute_number (attribute_id, value_number, requirement_id),
    KEY idx_procurement_requirement_attribute_option (attribute_id, value_option_id, requirement_id),
    KEY idx_procurement_requirement_attribute_text (attribute_id, value_text(100), requirement_id),
    CONSTRAINT fk_procurement_requirement_attribute_requirement FOREIGN KEY (requirement_id) REFERENCES procurement_requirements (id) ON DELETE CASCADE,
    CONSTRAINT fk_procurement_requirement_attribute_attribute FOREIGN KEY (attribute_id) REFERENCES attributes (id) ON DELETE RESTRICT,
    CONSTRAINT fk_procurement_requirement_attribute_option FOREIGN KEY (value_option_id) REFERENCES attribute_options (id) ON DELETE RESTRICT,
    CONSTRAINT chk_procurement_requirement_attribute_bool CHECK (value_bool IS NULL OR value_bool IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE procurement_requirement_attribute_value_options (
    value_id BIGINT UNSIGNED NOT NULL,
    option_id BIGINT UNSIGNED NOT NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (value_id, option_id),
    KEY idx_procurement_requirement_attribute_options_option (option_id),
    CONSTRAINT fk_procurement_requirement_attribute_options_value FOREIGN KEY (value_id) REFERENCES procurement_requirement_attribute_values (id) ON DELETE CASCADE,
    CONSTRAINT fk_procurement_requirement_attribute_options_option FOREIGN KEY (option_id) REFERENCES attribute_options (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE procurement_requirement_files (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    requirement_id BIGINT UNSIGNED NOT NULL,
    user_file_id BIGINT UNSIGNED NOT NULL,
    sort_order INT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_procurement_requirement_file (requirement_id, user_file_id),
    UNIQUE KEY uk_procurement_requirement_file_order (requirement_id, sort_order),
    KEY idx_procurement_requirement_files_file (user_file_id),
    CONSTRAINT fk_procurement_requirement_files_requirement FOREIGN KEY (requirement_id) REFERENCES procurement_requirements (id) ON DELETE CASCADE,
    CONSTRAINT fk_procurement_requirement_files_file FOREIGN KEY (user_file_id) REFERENCES user_files (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE procurement_requirement_responses (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    requirement_id BIGINT UNSIGNED NOT NULL,
    supplier_user_id BIGINT UNSIGNED NOT NULL,
    message TEXT NULL,
    available_quantity DECIMAL(18, 3) NULL,
    lead_time_days INT UNSIGNED NULL,
    status TINYINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_procurement_requirement_supplier (requirement_id, supplier_user_id),
    KEY idx_procurement_requirement_responses_supplier (supplier_user_id, status),
    CONSTRAINT fk_procurement_requirement_responses_requirement FOREIGN KEY (requirement_id) REFERENCES procurement_requirements (id) ON DELETE CASCADE,
    CONSTRAINT fk_procurement_requirement_responses_supplier FOREIGN KEY (supplier_user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT chk_procurement_requirement_response_status CHECK (status IN (0, 1, 2, 3, 4)),
    CONSTRAINT chk_procurement_requirement_response_quantity CHECK (available_quantity IS NULL OR available_quantity >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
