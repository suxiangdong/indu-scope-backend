CREATE TABLE vip_plans (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500) NULL,
    level INT UNSIGNED NOT NULL DEFAULT 1,
    billing_cycle VARCHAR(16) NOT NULL DEFAULT 'month',
    duration_days INT UNSIGNED NOT NULL,
    price_fen INT UNSIGNED NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'CNY',
    auto_renew_enabled TINYINT UNSIGNED NOT NULL DEFAULT 0,
    status TINYINT UNSIGNED NOT NULL DEFAULT 1,
    sort_order INT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_vip_plans_code (code),
    KEY idx_vip_plans_status_sort (status, sort_order),
    CONSTRAINT chk_vip_plans_cycle CHECK (billing_cycle IN ('month', 'quarter', 'year', 'custom')),
    CONSTRAINT chk_vip_plans_price CHECK (price_fen > 0),
    CONSTRAINT chk_vip_plans_status CHECK (status IN (0, 1)),
    CONSTRAINT chk_vip_plans_auto_renew CHECK (auto_renew_enabled IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE vip_subscriptions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id BIGINT UNSIGNED NOT NULL,
    plan_id BIGINT UNSIGNED NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    auto_renew TINYINT UNSIGNED NOT NULL DEFAULT 0,
    provider VARCHAR(32) NOT NULL DEFAULT 'manual',
    provider_contract_id VARCHAR(128) NULL,
    start_at DATETIME(3) NULL,
    end_at DATETIME(3) NULL,
    next_billing_at DATETIME(3) NULL,
    canceled_at DATETIME(3) NULL,
    cancel_reason VARCHAR(500) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_vip_subscriptions_user_status (user_id, status),
    KEY idx_vip_subscriptions_next_billing (status, next_billing_at),
    CONSTRAINT fk_vip_subscriptions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_vip_subscriptions_plan FOREIGN KEY (plan_id) REFERENCES vip_plans (id) ON DELETE RESTRICT,
    CONSTRAINT chk_vip_subscriptions_status CHECK (status IN ('pending', 'active', 'paused', 'canceled', 'expired')),
    CONSTRAINT chk_vip_subscriptions_auto_renew CHECK (auto_renew IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE payment_orders (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_no VARCHAR(64) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    plan_id BIGINT UNSIGNED NOT NULL,
    subscription_id BIGINT UNSIGNED NULL,
    amount_fen INT UNSIGNED NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'CNY',
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    payment_method VARCHAR(32) NOT NULL DEFAULT 'wechat_miniapp',
    provider VARCHAR(32) NOT NULL DEFAULT 'wechatpay',
    provider_transaction_id VARCHAR(128) NULL,
    prepay_id VARCHAR(128) NULL,
    idempotency_key VARCHAR(128) NULL,
    expires_at DATETIME(3) NULL,
    paid_at DATETIME(3) NULL,
    closed_at DATETIME(3) NULL,
    metadata JSON NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_payment_orders_order_no (order_no),
    UNIQUE KEY uk_payment_orders_idempotency (user_id, idempotency_key),
    KEY idx_payment_orders_user_status (user_id, status),
    KEY idx_payment_orders_provider_transaction (provider, provider_transaction_id),
    CONSTRAINT fk_payment_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment_orders_plan FOREIGN KEY (plan_id) REFERENCES vip_plans (id) ON DELETE RESTRICT,
    CONSTRAINT fk_payment_orders_subscription FOREIGN KEY (subscription_id) REFERENCES vip_subscriptions (id) ON DELETE SET NULL,
    CONSTRAINT chk_payment_orders_status CHECK (status IN ('pending', 'paying', 'paid', 'failed', 'closed', 'refunded')),
    CONSTRAINT chk_payment_orders_amount CHECK (amount_fen > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE payment_events (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    provider VARCHAR(32) NOT NULL,
    event_id VARCHAR(128) NOT NULL,
    order_no VARCHAR(64) NULL,
    event_type VARCHAR(64) NOT NULL,
    payload JSON NOT NULL,
    process_status VARCHAR(16) NOT NULL DEFAULT 'pending',
    processed_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_payment_events_provider_event (provider, event_id),
    KEY idx_payment_events_order_no (order_no),
    CONSTRAINT chk_payment_events_status CHECK (process_status IN ('pending', 'processed', 'failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
